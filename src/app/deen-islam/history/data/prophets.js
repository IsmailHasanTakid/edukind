export function storiesByTheme(themeId) {
    if (!themeId || themeId === "all") return STORIES;
    return STORIES.filter((story) => story.themes.includes(themeId));
}

export function matchesQuery(story, rawQuery) {
    const query = rawQuery.trim().toLowerCase();
    if (!query) return true;

    const themeLabels = story.themes
        .map((id) => THEME_MAP[id]?.label ?? "")
        .join(" ");

    const haystack = [
        story.name,
        story.englishName,
        story.honorific,
        story.epithet,
        story.title,
        story.summary,
        story.category,
        themeLabels,
        ...story.refs.map((ref) => formatRef(ref)),
    ]
        .join(" ")
        .toLowerCase();

    return haystack.includes(query);
}

