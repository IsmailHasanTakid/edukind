const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

export function toBn(value) {
    return String(value).replace(/\d/g, (digit) => BN_DIGITS[Number(digit)]);
}

export function formatRef(ref) {
    const name = SURAH_NAMES[ref.s];
    const range =
        ref.to && ref.to !== ref.from
            ? `${toBn(ref.from)}–${toBn(ref.to)}`
            : toBn(ref.from);

    return `সূরা ${name} ${toBn(ref.s)}:${range}`;
}

export function shortRef(ref) {
    const range =
        ref.to && ref.to !== ref.from
            ? `${toBn(ref.from)}–${toBn(ref.to)}`
            : toBn(ref.from);

    return `${toBn(ref.s)}:${range}`;
}

export function quranHref(ref) {
    return `/deen-islam/quran/${ref.s}`;
}

